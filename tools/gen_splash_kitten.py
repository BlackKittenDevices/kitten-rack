"""Kitten Rack boot splash -> firmware/src/splash_art.h (same format as tools/gen_splash.py).

  tools/gen_splash_kitten.py [OUT] [--png PREVIEW.png]

LOGO  a black cat sitting in front of an orange moon, drawn with Pillow at 4x and box-filtered down
WORD  "Kitten Rack" in a condensed bold face, bone and orange

Needs Pillow and the DejaVu fonts. The encoder (palette of 16 colours, run lengths) is gen_splash.py's.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
BG565 = 0x0841                     # C_BG in firmware/src/ui.c (warm black): keep in step


def _encoder():
    """gen_splash.py's encoder (rgb565, unpack, quantize, rle, emit) without running that script"""
    src = (ROOT / "tools" / "gen_splash.py").read_text()
    start = src.index("def rgb565(")
    end = src.index("\ntext = ")
    ns = {"BG565": BG565, "NCOL": 16, "sys": sys}
    head = src[:src.index("def png_rgba(")]
    for line in head.splitlines():
        if line.startswith("NCOL"):
            exec(line, ns)
    exec(src[start:end], ns)
    return ns


ENC = _encoder()
BG = tuple(int(v) for v in ENC["unpack"](BG565))
MOON = (255, 122, 26)
MOON_DARK = (214, 92, 18)
CAT = (10, 8, 7)
EYE = (255, 206, 64)
BONE = (232, 220, 194)
SS = 4
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf"


def logo():
    w, h = 150, 140
    im = Image.new("RGB", (w * SS, h * SS), BG)
    d = ImageDraw.Draw(im)
    s = lambda *v: [x * SS for x in v]  # noqa: E731
    d.ellipse(s(15, 4, 135, 124), fill=MOON)
    for cx, cy, r in ((44, 34, 9), (100, 26, 6), (112, 70, 8), (36, 84, 5)):
        d.ellipse(s(cx - r, cy - r, cx + r, cy + r), fill=MOON_DARK)
    # the tail, a thick curl to the right
    d.arc(s(84, 80, 140, 136), start=180, end=330, fill=CAT, width=9 * SS)
    d.ellipse(s(128, 92, 138, 102), fill=CAT)
    # body and haunches
    d.ellipse(s(44, 66, 108, 140), fill=CAT)
    d.ellipse(s(38, 104, 70, 140), fill=CAT)
    d.ellipse(s(82, 104, 114, 140), fill=CAT)
    # head and ears
    d.ellipse(s(48, 32, 104, 82), fill=CAT)
    d.polygon(s(50, 52, 52, 18, 72, 38), fill=CAT)
    d.polygon(s(102, 52, 100, 18, 80, 38), fill=CAT)
    # eyes: almonds with a slit
    for ex in (65, 87):
        d.ellipse(s(ex - 7, 50, ex + 7, 59), fill=EYE)
        d.ellipse(s(ex - 1.3, 50.5, ex + 1.3, 58.5), fill=CAT)
    return im.resize((w, h), Image.BOX)


def word():
    w, h = 216, 45
    big = Image.new("RGB", (w * SS, h * SS), BG)
    d = ImageDraw.Draw(big)
    font = ImageFont.truetype(FONT, 44 * SS)
    parts = (("KITTEN ", BONE), ("RACK", MOON))
    widths = [d.textlength(t, font=font) for t, _ in parts]
    total = sum(widths)
    x = 0
    # draw on a wide canvas, then squeeze to 216 px
    canvas = Image.new("RGB", (int(total) + 8 * SS, h * SS), BG)
    cd = ImageDraw.Draw(canvas)
    for (t, col), tw in zip(parts, widths):
        cd.text((x, h * SS / 2), t, font=font, fill=col, anchor="lm")
        x += tw
    return canvas.resize((w, h), Image.BOX)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--png")]
    out = Path(args[0]) if args and not args[0].endswith(".png") else ROOT / "firmware" / "src" / "splash_art.h"
    lg, wd = logo(), word()
    if "--png" in sys.argv:
        prev = Image.new("RGB", (240, 240), BG)
        prev.paste(lg, ((240 - lg.width) // 2, 4))
        prev.paste(wd, ((240 - wd.width) // 2, 151))
        prev.resize((720, 720), Image.NEAREST).save(sys.argv[sys.argv.index("--png") + 1])
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* Generated by tools/gen_splash_kitten.py: the Kitten Rack boot art (splash.c). Do not edit. */",
        "typedef struct { uint16_t w, h; const uint16_t *pal; const uint8_t *rle; uint32_t len; } splash_art_t;",
    ]
    for name, im in (("SPLASH_LOGO", lg), ("SPLASH_WORD", wd)):
        px = [tuple(float(c) for c in p) for p in im.getdata()]
        lines.append(ENC["emit"](name, im.width, im.height, px))
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
